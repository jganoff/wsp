    fn make_metadata(repos: &[&str]) -> Metadata {
        let mut map = BTreeMap::new();
        for id in repos {
            map.insert(id.to_string(), None);
        }
        Metadata {
            version: 0,
            name: "test".into(),
            branch: "test".into(),
            repos: map,
            created: Utc::now(),
            description: None,
            last_used: None,
            created_from: None,
            dirs: BTreeMap::new(),
            config: None,
        }
    }

    fn make_metadata_with_refs(repos: &[(&str, Option<&str>)]) -> Metadata {
        let mut map: BTreeMap<String, Option<WorkspaceRepoRef>> = BTreeMap::new();
        for (id, r) in repos {
            match r {
                None => {
                    map.insert(id.to_string(), None);
                }
                Some(ref_str) => {
                    map.insert(
                        id.to_string(),
                        Some(WorkspaceRepoRef {
                            r#ref: ref_str.to_string(),
                            url: None,
                        }),
                    );
                }
            }
        }
        Metadata {
            version: 0,
            name: "test".into(),
            branch: "test".into(),
            repos: map,
            created: Utc::now(),
            description: None,
            last_used: None,
            created_from: None,
            dirs: BTreeMap::new(),
            config: None,
        }
    }

