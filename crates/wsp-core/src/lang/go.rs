use std::fmt;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use crate::workspace::Metadata;

use super::LanguageIntegration;

const DEFAULT_GO_VERSION: GoVersion = GoVersion {
    major: 1,
    minor: 21,
    patch: None,
};

pub const GO_WORK_HEADER: &str = "// Code generated by wsp. DO NOT EDIT.";

pub struct GoIntegration;

impl LanguageIntegration for GoIntegration {
    fn name(&self) -> &str {
        "go"
    }

    fn detect(&self, ws_dir: &Path, metadata: &Metadata) -> bool {
        repo_dirs(ws_dir, metadata)
            .iter()
            .any(|(name, path)| !find_go_modules(path, name).is_empty())
    }

    fn apply(&self, ws_dir: &Path, metadata: &Metadata) -> Result<()> {
        let dirs = repo_dirs(ws_dir, metadata);
        let mut entries: Vec<(String, GoVersion)> = Vec::new();

        for (name, path) in &dirs {
            for mod_rel in find_go_modules(path, name) {
                let go_mod = ws_dir.join(&mod_rel).join("go.mod");
                let content = fs::read_to_string(&go_mod)
                    .with_context(|| format!("reading {}", go_mod.display()))?;
                let version = parse_go_version(&content).unwrap_or(DEFAULT_GO_VERSION);
                entries.push((mod_rel, version));
            }
        }

        if entries.is_empty() {
            return Ok(());
        }

        let max_version = entries
            .iter()
            .map(|(_, v)| v)
            .max()
            .cloned()
            .unwrap_or(DEFAULT_GO_VERSION);

        let mut names: Vec<&str> = entries.iter().map(|(n, _)| n.as_str()).collect();
        names.sort();

        let mut out = String::new();
        out.push_str(GO_WORK_HEADER);
        out.push('\n');
        out.push_str(&format!("go {}\n", max_version));
        out.push('\n');
        out.push_str("use (\n");
        for name in &names {
            out.push_str(&format!("\t./{}\n", name));
        }
        out.push_str(")\n");

        let tmp_path = ws_dir.join(".go.work.tmp");
        let final_path = ws_dir.join("go.work");
        fs::write(&tmp_path, out).with_context(|| format!("writing {}", tmp_path.display()))?;
        fs::rename(&tmp_path, &final_path).with_context(|| {
            format!(
                "renaming {} to {}",
                tmp_path.display(),
                final_path.display()
            )
        })?;
        Ok(())
    }
}

/// Returns (dir_name, repo_path) for all repos in the workspace.
fn repo_dirs(ws_dir: &Path, metadata: &Metadata) -> Vec<(String, PathBuf)> {
    let mut result = Vec::new();
    for identity in metadata.repos.keys() {
        if let Ok(dn) = metadata.dir_name(identity) {
            if dn.contains("..") || dn.starts_with('/') {
                continue;
            }
            let path = ws_dir.join(&dn);
            result.push((dn, path));
        }
    }
    result
}

/// Directories to skip when walking for go.mod files.
const SKIP_DIRS: &[&str] = &[".git", "vendor", "testdata", "node_modules"];

/// Recursively finds all `go.mod` files under `root`.
/// Returns workspace-relative paths (e.g. `repo-name/services/api`).
fn find_go_modules(root: &Path, repo_name: &str) -> Vec<String> {
    let mut results = Vec::new();
    walk_for_go_mod(root, repo_name, &mut results);
    results
}

fn walk_for_go_mod(dir: &Path, rel_path: &str, results: &mut Vec<String>) {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };

    let is_regular_file = dir
        .join("go.mod")
        .symlink_metadata()
        .map(|m| m.file_type().is_file())
        .unwrap_or(false);
    if is_regular_file {
        results.push(rel_path.to_string());
    }

    let mut subdirs: Vec<_> = entries
        .filter_map(|e| e.ok())
        .filter(|e| e.file_type().map(|ft| ft.is_dir()).unwrap_or(false))
        .filter(|e| {
            let name = e.file_name();
            let name = name.to_string_lossy();
            !name.starts_with('.') && !SKIP_DIRS.contains(&name.as_ref())
        })
        .collect();
    subdirs.sort_by_key(|e| e.file_name());

    for entry in subdirs {
        let child_rel = format!("{}/{}", rel_path, entry.file_name().to_string_lossy());
        walk_for_go_mod(&entry.path(), &child_rel, results);
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GoVersion {
    pub major: u32,
    pub minor: u32,
    pub patch: Option<u32>,
}

impl Ord for GoVersion {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        self.major
            .cmp(&other.major)
            .then(self.minor.cmp(&other.minor))
            .then(self.patch.unwrap_or(0).cmp(&other.patch.unwrap_or(0)))
    }
}

impl PartialOrd for GoVersion {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

impl fmt::Display for GoVersion {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.patch {
            Some(p) => write!(f, "{}.{}.{}", self.major, self.minor, p),
            None => write!(f, "{}.{}", self.major, self.minor),
        }
    }
}

/// Parses the `go X.Y` or `go X.Y.Z` directive from go.mod content.
pub fn parse_go_version(content: &str) -> Option<GoVersion> {
    for line in content.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("go ") {
            let rest = rest.trim();
            let parts: Vec<&str> = rest.split('.').collect();
            if parts.len() >= 2
                && let (Ok(major), Ok(minor)) = (parts[0].parse(), parts[1].parse())
            {
                let patch = if parts.len() >= 3 {
                    parts[2].parse().ok()
                } else {
                    None
                };
                return Some(GoVersion {
                    major,
                    minor,
                    patch,
                });
            }
        }
    }
    None
}

